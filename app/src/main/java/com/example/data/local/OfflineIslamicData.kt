    fun normalizeArabic(text: String): String {
        return text
            .replace(Regex("[\u064B-\u065F\u0670\u0640]"), "")
            .replace('أ', 'ا')
            .replace('إ', 'ا')
            .replace('آ', 'ا')
            .replace('ٱ', 'ا')
            .replace('ة', 'ه')
            .replace('ى', 'ي')
            .trim()
    }

